package dao;

import java.sql.Connection;
import java.sql.Date;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

import model.Invoice;
import model.InvoiceItem;

public class InvoiceDao implements Dao<Invoice> {

    /**
     * Saves an invoice, its items and its unique number as one transaction.
     * If any step fails, everything is rolled back and nothing is saved.
     */
    @Override
    public void add(Invoice invoice) throws SQLException {
        try (Connection con = DBConnection.getConnection()) {
            con.setAutoCommit(false);
            try {
                invoice.setId(insertInvoice(con, invoice));
                invoice.setInvoiceNumber(String.format("INV-%d-%04d", invoice.getIssueDate().getYear(), invoice.getId()));
                saveInvoiceNumber(con, invoice);
                insertItems(con, invoice);
                con.commit();
            } catch (SQLException e) {
                con.rollback();
                throw e;
            }
        }
    }

    @Override
    public List<Invoice> getAll() throws SQLException {
        Map<Integer, List<InvoiceItem>> itemsByInvoice = loadItems();
        List<Invoice> list = new ArrayList<>();
        String sql = "SELECT i.invoice_id, i.invoice_number, i.freelancer_id, i.client_id, "
                + "f.name AS freelancer_name, c.name AS client_name, i.issue_date, i.due_date, i.tax_percent, "
                + "(SELECT COALESCE(SUM(p.amount), 0) FROM payments p WHERE p.invoice_id = i.invoice_id) AS paid "
                + "FROM invoices i "
                + "JOIN freelancers f ON f.freelancer_id = i.freelancer_id "
                + "JOIN clients c ON c.client_id = i.client_id "
                + "ORDER BY i.invoice_id DESC";
        try (Connection con = DBConnection.getConnection();
             Statement st = con.createStatement();
             ResultSet rs = st.executeQuery(sql)) {
            while (rs.next()) {
                Invoice invoice = new Invoice(rs.getInt("freelancer_id"), rs.getInt("client_id"),
                        rs.getDate("issue_date").toLocalDate(), rs.getDate("due_date").toLocalDate(),
                        rs.getDouble("tax_percent"));
                invoice.setId(rs.getInt("invoice_id"));
                invoice.setInvoiceNumber(rs.getString("invoice_number"));
                invoice.setFreelancerName(rs.getString("freelancer_name"));
                invoice.setClientName(rs.getString("client_name"));
                invoice.setPaidAmount(rs.getDouble("paid"));
                itemsByInvoice.getOrDefault(invoice.getId(), List.of()).forEach(invoice::addItem);
                list.add(invoice);
            }
        }
        return list;
    }

    // Step 1: insert the invoice row and return the id generated by the database
    private int insertInvoice(Connection con, Invoice invoice) throws SQLException {
        String sql = "INSERT INTO invoices (freelancer_id, client_id, issue_date, due_date, tax_percent) "
                + "VALUES (?, ?, ?, ?, ?)";
        try (PreparedStatement ps = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {
            ps.setInt(1, invoice.getFreelancerId());
            ps.setInt(2, invoice.getClientId());
            ps.setDate(3, Date.valueOf(invoice.getIssueDate()));
            ps.setDate(4, Date.valueOf(invoice.getDueDate()));
            ps.setDouble(5, invoice.getTaxPercent());
            ps.executeUpdate();
            try (ResultSet keys = ps.getGeneratedKeys()) {
                keys.next();
                return keys.getInt(1);
            }
        }
    }

    // Step 2: store the unique invoice number built from the generated id
    private void saveInvoiceNumber(Connection con, Invoice invoice) throws SQLException {
        String sql = "UPDATE invoices SET invoice_number = ? WHERE invoice_id = ?";
        try (PreparedStatement ps = con.prepareStatement(sql)) {
            ps.setString(1, invoice.getInvoiceNumber());
            ps.setInt(2, invoice.getId());
            ps.executeUpdate();
        }
    }

    // Step 3: insert every line of the invoice
    private void insertItems(Connection con, Invoice invoice) throws SQLException {
        String sql = "INSERT INTO invoice_items (invoice_id, description, quantity, unit_rate) VALUES (?, ?, ?, ?)";
        try (PreparedStatement ps = con.prepareStatement(sql)) {
            for (InvoiceItem item : invoice.getItems()) {
                ps.setInt(1, invoice.getId());
                ps.setString(2, item.getDescription());
                ps.setInt(3, item.getQuantity());
                ps.setDouble(4, item.getUnitRate());
                ps.executeUpdate();
            }
        }
    }

    // Reads all items once and groups them by invoice id in a HashMap
    private Map<Integer, List<InvoiceItem>> loadItems() throws SQLException {
        Map<Integer, List<InvoiceItem>> map = new HashMap<>();
        String sql = "SELECT invoice_id, description, quantity, unit_rate FROM invoice_items";
        try (Connection con = DBConnection.getConnection();
             Statement st = con.createStatement();
             ResultSet rs = st.executeQuery(sql)) {
            while (rs.next()) {
                InvoiceItem item = new InvoiceItem(rs.getString("description"),
                        rs.getInt("quantity"), rs.getDouble("unit_rate"));
                map.computeIfAbsent(rs.getInt("invoice_id"), id -> new ArrayList<>()).add(item);
            }
        }
        return map;
    }
}
